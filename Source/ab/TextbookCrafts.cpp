namespace
{
    FTextbookPage Deed(const TCHAR* Title, const TCHAR* Text, const TCHAR* Craft, std::initializer_list<const TCHAR*> Shown)
    {
        FTextbookPage P = Page(Title, Text, 0.15f);
        P.Craft = Craft ? FName(Craft) : NAME_None;
        for (const TCHAR* Thing : Shown)
        {
            P.Pictures.Add(Thing);
        }
        return P;
    }
}

