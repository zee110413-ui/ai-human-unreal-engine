#include "Textbook.h"

namespace
{
    FTextbookPage Page(const TCHAR* Title, const TCHAR* Text, float Difficulty)
    {
        FTextbookPage P;
        P.Title = Title;
        P.Text = Text;
        P.Difficulty = Difficulty;
        return P;
    }

    FTextbook Book(const TCHAR* Subject, const TCHAR* Title, const TCHAR* Course,
                   const TCHAR* Skill, const TCHAR* Second, float Difficulty,
                   float RequiredReading, TArray<FTextbookPage> Pages)
    {
        FTextbook B;
        B.Subject = Subject;
        B.Title = Title;
        B.Course = Course;
        B.Skill = Skill;
        B.SecondSkill = Second;
        B.Topic = EWordTopic::Work;
        B.Difficulty = Difficulty;
        B.RequiredReading = RequiredReading;
        B.Pages = MoveTemp(Pages);
        return B;
    }
}

