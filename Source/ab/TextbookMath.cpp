#include "Textbook.h"

namespace
{
    FTextbookPage Para(const TCHAR* Title, const TCHAR* Text, float Difficulty)
    {
        FTextbookPage Page;
        Page.Title = Title;
        Page.Text = Text;
        Page.Difficulty = Difficulty;
        return Page;
    }

    FTextbook Book(const TCHAR* Subject, int32 Grade, const TCHAR* Skill,
                   const TCHAR* Second, float Difficulty, float Reading,
                   TArray<FTextbookPage> Pages)
    {
        FTextbook B;
        B.Subject = Subject;
        B.Course = TEXT("математика");
        B.Grade = Grade;
        B.Title = FString::Printf(TEXT("математика, %d класс"), Grade);
        B.Skill = Skill;
        B.SecondSkill = Second;
        B.Topic = EWordTopic::Thought;
        B.Difficulty = Difficulty;
        B.RequiredReading = Reading;
        B.Pages = MoveTemp(Pages);
        return B;
    }
}

