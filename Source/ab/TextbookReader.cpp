// TextbookReader.cpp
// ---------------------------------------------------------------------------
// «Родная речь» — книга для чтения.
//
// Слов у жителей нет, пока они их не прочитают. Учебник русского учит
// правилам, а говорить о жизни учит эта книга: как здороваться, как спросить
// дорогу, как сказать, что хочется есть, как утешить и как попрощаться.
// ---------------------------------------------------------------------------

#include "Textbook.h"

namespace
{
    FTextbookPage ReaderPage(const TCHAR* Title, const TCHAR* Text, float Difficulty)
    {
        FTextbookPage Page;
        Page.Title = Title;
        Page.Text = Text;
        Page.Difficulty = Difficulty;
        return Page;
    }
}

