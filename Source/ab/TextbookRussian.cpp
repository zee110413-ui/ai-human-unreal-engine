// Учебник русского языка, с первого по седьмой класс.
//
// Это настоящая книга: параграф за параграфом, с правилом, примерами и
// упражнением — так, как учебники и пишут. Человек читает её глазами,
// слово за словом, со своей скоростью, и останавливается там, где его
// застал вечер. Назавтра он продолжит с того же места.
//
// Правила изложены заново, своими словами, но правила от этого не меняются.
// ---------------------------------------------------------------------------

#include "Textbook.h"

namespace
{
    FTextbookPage Para(const TCHAR* Title, const TCHAR* Text, float Difficulty)
    {
        FTextbookPage Page;
        Page.Title = Title;
        Page.Text = Text;
        Page.Difficulty = Difficulty;
        return Page;
    }

    FTextbook Book(const TCHAR* Subject, int32 Grade, const TCHAR* Skill,
                   const TCHAR* Second, float Difficulty, float Reading,
                   TArray<FTextbookPage> Pages)
    {
        FTextbook B;
        B.Subject = Subject;
        B.Course = TEXT("русский язык");
        B.Grade = Grade;
        B.Title = FString::Printf(TEXT("русский язык, %d класс"), Grade);
        B.Skill = Skill;
        B.SecondSkill = Second;
        B.Topic = EWordTopic::Speech;
        B.Difficulty = Difficulty;
        B.RequiredReading = Reading;
        B.Pages = MoveTemp(Pages);
        return B;
    }
}

